// Writes docs/DATA_AVAILABILITY.md from the committed data. Run: npm run data:availability
// Nothing here is shown on the site; it is a report for the builder and the owner.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { CountriesFile, DataMeta, DataRecord, IndicatorMeta, MedianRecord } from '../src/data/types.ts';
import { COUNTRY, DEFAULT_PEERS, INDICATORS } from './indicators.ts';
import { ROOT, countriesPath, indicatorsPath, medianPath, metaPath, processedPath, readJson } from './lib/files.ts';

/** "In the last ten years" = this calendar year minus ten, or later. */
const meta = readJson<DataMeta>(metaPath())!;
const thisYear = Number(meta.last_checked.slice(0, 4));
const since = thisYear - 10;

const countries = readJson<CountriesFile>(countriesPath())!;
const name = (id: string) => countries.countries.find((c) => c.id === id)?.name ?? id;
const metas = readJson<IndicatorMeta[]>(indicatorsPath())!;

const latestBy = (rs: DataRecord[]) => {
  const m = new Map<string, number>();
  for (const r of rs) m.set(r.country, Math.max(m.get(r.country) ?? 0, r.year));
  return m;
};

const lines: string[] = [];
lines.push('# Data availability (P0 indicators)');
lines.push('');
lines.push(`Generated by \`npm run data:availability\` from the data last checked on ${meta.last_checked}.`);
lines.push(`"Last 10 years" means ${since} or later. Peers are the ${DEFAULT_PEERS.length} default peers (${DEFAULT_PEERS.map(name).join(', ')}).`);
lines.push('Rule (section 5.3): drop an indicator if Bangladesh has no usable data or fewer than 3 peers have data in the last 10 years.');
lines.push('');
lines.push('| Indicator | Code | Bangladesh latest year | Peers with data since ' + since + ' | Peers without | LMIC median: years / latest (countries) | Caveats |');
lines.push('|---|---|---|---|---|---|---|');

const thin: string[] = [];
for (const config of INDICATORS) {
  const records = readJson<DataRecord[]>(processedPath(config.id)) ?? [];
  const latest = latestBy(records);
  const bgd = latest.get(COUNTRY);
  const caveats = new Set<string>();
  const m = metas.find((x) => x.id === config.id);
  if (/model/i.test(m?.source_series_name ?? '')) caveats.add('modelled estimate (in the series name)');
  if (/gross/i.test(m?.source_series_name ?? '')) caveats.add('gross figure, can exceed 100%');
  if (config.unit === 'taka_current' || config.unit === 'taka_constant') caveats.add('Bangladesh only (local currency)');
  const noteCount = new Set(records.flatMap((r) => r.notes)).size;
  if (noteCount > 0) caveats.add(`${noteCount} different publisher note(s)`);
  // Survey-based series: years with data are far apart.
  const bgdYears = records.filter((r) => r.country === COUNTRY).map((r) => r.year);
  if (bgdYears.length > 0 && bgdYears.length < (Math.max(...bgdYears) - Math.min(...bgdYears) + 1) / 2) {
    caveats.add(`Bangladesh data only in some years (${bgdYears.length} years)`);
  }

  let peerCell = 'n/a';
  let withoutCell = 'n/a';
  let medianCell = 'n/a';
  if (config.scope === 'compare') {
    const withData = DEFAULT_PEERS.filter((p) => (latest.get(p) ?? 0) >= since);
    const without = DEFAULT_PEERS.filter((p) => !withData.includes(p));
    peerCell = `${withData.length} of ${DEFAULT_PEERS.length}: ${withData.map((p) => `${name(p)} ${latest.get(p)}`).join(', ')}`;
    withoutCell = without.length ? without.map((p) => `${name(p)}${latest.has(p) ? ` (last ${latest.get(p)})` : ' (none)'}`).join(', ') : 'none';
    if (withData.length < 3) thin.push(`${config.id}: only ${withData.length} peers since ${since}`);
    else if (withData.length < DEFAULT_PEERS.length) thin.push(`${config.id}: ${withData.length} of ${DEFAULT_PEERS.length} peers since ${since}`);
    const medians = readJson<MedianRecord[]>(medianPath(config.id)) ?? [];
    const last = medians.at(-1);
    medianCell = last ? `${medians.length} / ${last.year} (${last.inputs.length})` : 'no year has enough countries';
  }
  lines.push(
    `| ${config.id} | ${config.code} | ${bgd ?? '**none**'} | ${peerCell} | ${withoutCell} | ${medianCell} | ${[...caveats].join('; ') || '-'} |`,
  );
}

lines.push('');
lines.push('## Thin peer data');
lines.push('');
lines.push(thin.length ? thin.map((t) => `- ${t}`).join('\n') : 'Every comparable indicator has data for all peers since ' + since + '.');
lines.push('');
lines.push('## Peer income groups (read from the World Bank country list)');
lines.push('');
for (const id of [COUNTRY, ...DEFAULT_PEERS]) {
  const c = countries.countries.find((x) => x.id === id)!;
  lines.push(`- ${c.name}: ${c.income_group_name}`);
}
lines.push('');
lines.push(`Classification source: ${countries.classification_url} (list retrieved ${countries.retrieved_at}).`);
lines.push('');

writeFileSync(resolve(ROOT, 'docs/DATA_AVAILABILITY.md'), lines.join('\n'), 'utf8');
console.log('Wrote docs/DATA_AVAILABILITY.md');
if (thin.length) console.log(thin.join('\n'));
